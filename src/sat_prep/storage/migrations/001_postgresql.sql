CREATE TABLE IF NOT EXISTS profile (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    name TEXT NOT NULL DEFAULT 'Student',
    target_minutes INTEGER NOT NULL DEFAULT 20
);
INSERT INTO profile (id, name, target_minutes) VALUES (1, 'Student', 20) ON CONFLICT (id) DO NOTHING;
CREATE TABLE IF NOT EXISTS sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TEXT NOT NULL,
    completed_at TEXT,
    duration_seconds INTEGER NOT NULL DEFAULT 0,
    completed INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS answers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id INTEGER NOT NULL REFERENCES sessions(id),
    question_id TEXT NOT NULL,
    skill TEXT NOT NULL,
    module TEXT NOT NULL,
    selected_answer TEXT NOT NULL,
    is_correct INTEGER NOT NULL,
    answered_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS preparation_plan (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    graduation_year INTEGER NOT NULL DEFAULT 2030,
    target_score INTEGER NOT NULL DEFAULT 1400
);
INSERT INTO preparation_plan (id) VALUES (1) ON CONFLICT (id) DO NOTHING;
CREATE TABLE IF NOT EXISTS score_reports (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_type TEXT NOT NULL,
    test_date TEXT NOT NULL,
    reading_writing INTEGER NOT NULL,
    math INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS answers_session_idx ON answers (session_id);
CREATE INDEX IF NOT EXISTS answers_answered_at_idx ON answers (answered_at);
